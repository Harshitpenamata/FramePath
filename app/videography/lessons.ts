// Lessons inside a module: one per curriculum topic. Each lesson has Watch (an idea and videos)
// and Reflect (a small interactive tool). Beginner modules have lessons; other levels show the module's videos.
export type Tool=
 |{kind:'order';prompt:string;items:string[];why:string}
 |{kind:'sort';prompt:string;groups:string[];items:[string,number][];why:string}
 |{kind:'pick';prompt:string;options:[string,boolean,string][]}
 |{kind:'spot';prompt:string;look?:'list'|'timeline';items:[string,boolean][];why:string}
 |{kind:'exposure';prompt:string;goal:'moving'|'clean'}
 |{kind:'whitebalance';prompt:string;cast:'warm'|'cool'}
 |{kind:'mix';prompt:string;music:boolean}
 |{kind:'frame';prompt:string;goal:'thirds'|'close'};
type VideoRef=keyof typeof V|'pathway0'|'pathway1';
export type ModuleLessonItem={title:string;idea:string;videos?:VideoRef[];tool:Tool};

const order=(prompt:string,items:string[],why:string):Tool=>({kind:'order',prompt,items,why});
const sort=(prompt:string,groups:string[],items:[string,number][],why:string):Tool=>({kind:'sort',prompt,groups,items,why});
const pick=(prompt:string,...options:[string,boolean,string][]):Tool=>({kind:'pick',prompt,options});
const spot=(prompt:string,items:[string,boolean][],why:string,look:'list'|'timeline'='list'):Tool=>({kind:'spot',prompt,items,why,look});
const L=(title:string,idea:string,tool:Tool,videos?:VideoRef[]):ModuleLessonItem=>({title,idea,tool,videos});

